export function icon(name, size = 18) {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("class", "icon");
  svg.setAttribute("width", size);
  svg.setAttribute("height", size);
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "2");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  svg.innerHTML = ICONS[name] ?? "";
  return svg;
}

// ---------- Feedback ----------

export function toast(text, kind = "ok") {
  let box = document.getElementById("toasts");
  if (!box) {
    box = h("div", { id: "toasts", className: "toasts", role: "status", "aria-live": "polite" });
    document.body.append(box);
  }
  const el = h("div", { className: `toast ${kind}` }, icon(kind === "err" ? "alert" : "check"), text);
  box.append(el);
  while (box.children.length > 3) box.firstChild.remove();
  setTimeout(() => el.remove(), 4200);
}

// Native <dialog> modal. `build(close)` returns the form element to show.
export function openDialog(build) {
  const dialog = h("dialog", { className: "modal" });
  const close = () => dialog.close();
  dialog.append(build(close));
  dialog.addEventListener("close", () => dialog.remove());
  dialog.addEventListener("click", (e) => {
    if (e.target === dialog) close(); // click on the backdrop
  });
  document.body.append(dialog);
  dialog.showModal();
  return dialog;
}

// ---------- Formatting ----------

export const initials = (name, email = "") => {
  const words = (name || email.split("@")[0] || "?").trim().split(/\s+/);
  return (words[0][0] + (words.length > 1 ? words.at(-1)[0] : "")).toUpperCase();
};

export const avatar = (name, email, size = 40) =>
  h("span", { className: "avatar", style: `--size:${size}px`, "aria-hidden": "true" }, initials(name, email));

// SQLite stores UTC as "YYYY-MM-DD HH:MM:SS".
export const fmtDate = (s) =>
  s
    ? new Date(`${s.replace(" ", "T")}Z`).toLocaleDateString(undefined, {
        month: "short",
        day: "numeric",
        year: "numeric",
      })
    : "";

// Due dates are plain "YYYY-MM-DD" and mean that calendar day locally.
export function parseDay(s) {
  const [y, m, d] = s.split("-").map(Number);
  return new Date(y, m - 1, d);
}
export const fmtDay = (s) =>
  parseDay(s).toLocaleDateString(undefined, { month: "short", day: "numeric", year: "numeric" });
